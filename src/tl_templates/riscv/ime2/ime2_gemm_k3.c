#include <omp.h>
#endif
#define KB 16

/* A: 每 16 行一块，每 k 块 256B（16 行 x 16B 连续） */
static void pack_a16(int M, int K, const int8_t *A, int8_t *Ap) {
    int m16 = M / 16, ks = K / KB;
    for (int i = 0; i < m16; i++)
        for (int t = 0; t < ks; t++) {
            int8_t *dst = Ap + ((size_t)i * ks + t) * 256;
            for (int r = 0; r < 16; r++)
                memcpy(dst + r * 16, A + (size_t)(i * 16 + r) * K + (size_t)t * KB, 16);
        }
}
/* B: 每 32 列一块，每 k 块 512B（32 列 x 16B 连续） */
static void pack_b32(int N, int K, const int8_t *B, int8_t *Bp) {
    int n32 = N / 32, ks = K / KB;
    for (int j = 0; j < n32; j++)
        for (int t = 0; t < ks; t++) {
            int8_t *dst = Bp + ((size_t)j * ks + t) * 512;
            for (int c = 0; c < 32; c++)
                for (int k = 0; k < 16; k++)
                    dst[c * 16 + k] = B[(size_t)(t * KB + k) * N + (j * 32 + c)];
        }
}
void ime2_pack(int M, int N, int K, const int8_t *A, const int8_t *B, int8_t *Ap, int8_t *Bp) {
    pack_a16(M, K, A, Ap);
    pack_b32(N, K, B, Bp);
}

