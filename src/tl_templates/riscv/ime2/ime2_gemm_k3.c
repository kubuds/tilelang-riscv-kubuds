// ime2_gemm_v3.c —— 把 6 条载入合并成 2 条（LMUL=2 载 A 双面板，LMUL=4 载 B 四面板）
//
// 动机（docs/05 第九/十轮）：单核 174 周期/k 步，恰好等于「6 条载入 x 30 周期」，
// 说明核心对向量 miss 的排队能力很浅，6 条独立流排队等 L2。超订线程（12/16/24）反而更慢，
// 排除用第二个线程藏延迟。于是改打包布局，让同一 k 块的多个面板在内存里连续：
//   A: 每 k 块 256B = 16 行 x 16 k  → 一条 e8/m2 载入进 v0,v1
//   B: 每 k 块 512B = 32 列 x 16 k  → 一条 e8/m4 载入进 v2..v5
// 每步载入指令 6 → 2，miss 数同比降。
//
// 参考：[1] docs/05 vmadot 语义（A=8 行/寄存器，B=8 列/寄存器）
//       [2] RISC-V V 1.0：LMUL=2/4 的 VLMAX 与寄存器组连续性
#include <stdint.h>
#include <stdlib.h>
